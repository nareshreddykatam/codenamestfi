export const TELUGU_MOVIES: string[] = TELUGU_MOVIE_ENTRIES.map(e => e.title);

/**
 * Utility to retrieve a guaranteed unique set of 25 Telugu movie entries
 */
export function getRandomTeluguMovieEntries(count: number = 25): MovieEntry[] {
  // Deduplicate by title
  const seen = new Set<string>();
  const uniqueEntries: MovieEntry[] = [];

  for (const entry of TELUGU_MOVIE_ENTRIES) {
    const cleanTitle = entry.title.trim();
    if (cleanTitle && !seen.has(cleanTitle.toLowerCase())) {
      seen.add(cleanTitle.toLowerCase());
      uniqueEntries.push({ title: cleanTitle, image: entry.image });
    }
  }

  if (uniqueEntries.length < count) {
    throw new Error(`Movie database has fewer than ${count} unique titles.`);
  }

  // Fisher-Yates shuffle
  const shuffled = [...uniqueEntries];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}

/**
 * Backward compatibility helper returning string titles
 */
export function getRandomTeluguMovies(count: number = 25): string[] {
  return getRandomTeluguMovieEntries(count).map(e => e.title);
}
